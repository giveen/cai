_PROBE_PAYLOAD = "/?__waf_probe=1'+OR+'1'='1&<script>alert(1)</script>"

# ---------------------------------------------------------------------------
# HTTP helper
# ---------------------------------------------------------------------------

def _fetch(url: str, extra_path: str = "", timeout: float = 8.0) -> tuple[int, dict[str, str], list[str], str]:
    """Return (status, headers_lower, cookies, body_lower) for GET *url*+*extra_path*.

    cookies is a list of Set-Cookie header values (lower-case).
    Returns (-1, {}, [], "") on error.
    """
    try:
        parsed = urllib.parse.urlparse(url)
        is_https = parsed.scheme == "https"
        host = parsed.netloc or parsed.path
        path = (parsed.path or "/") + extra_path
        if parsed.query:
            path += "?" + parsed.query

        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE

        conn_cls = http.client.HTTPSConnection if is_https else http.client.HTTPConnection
        conn = conn_cls(host, timeout=timeout, **({"context": ctx} if is_https else {}))
        try:
            conn.request(
                "GET",
                path,
                headers={
                    "User-Agent": "Mozilla/5.0 (compatible; waf-detector/1.0)",
                    "Accept": "text/html,*/*",
                },
            )
            resp = conn.getresponse()
            status = resp.status
            headers_raw = resp.getheaders()
            body_raw = resp.read(8192)
        finally:
            conn.close()

        headers: dict[str, str] = {}
        cookies: list[str] = []
        for name, value in headers_raw:
            name_l = name.lower()
            value_l = value.lower()
            headers[name_l] = value_l
            if name_l == "set-cookie":
                cookies.append(value_l)

        body = body_raw.decode("utf-8", errors="replace").lower()
        return status, headers, cookies, body

    except Exception:
        return -1, {}, [], ""


# ---------------------------------------------------------------------------
# Scoring engine
# ---------------------------------------------------------------------------

class WAFSignal(NamedTuple):
    waf_name: str
    source: str   # "header" | "cookie" | "body"
    detail: str


def _score_response(
    headers: dict[str, str],
    cookies: list[str],
    body: str,
    context: str,
) -> list[WAFSignal]:
    """Return all WAF signals detected in this HTTP response."""
    signals: list[WAFSignal] = []
    cookie_blob = " ".join(cookies)

    for entry in _WAF_DB:
        # Header fingerprints
        for hdr_name, hdr_value in entry.headers:
            if hdr_name in headers:
                if hdr_value is None or hdr_value in headers[hdr_name]:
                    signals.append(WAFSignal(
                        waf_name=entry.name,
                        source="header",
                        detail=f"[{context}] Header '{hdr_name}'" +
                               (f" contains '{hdr_value}'" if hdr_value else " present"),
                    ))
                    break  # one signal per WAF per response category

        # Cookie fingerprints
        for ck_name in entry.cookies:
            if ck_name in cookie_blob:
                signals.append(WAFSignal(
                    waf_name=entry.name,
                    source="cookie",
                    detail=f"[{context}] Cookie matches '{ck_name}'",
                ))
                break

        # Body fingerprints
        for marker in entry.body_markers:
            if marker in body:
                signals.append(WAFSignal(
                    waf_name=entry.name,
                    source="body",
                    detail=f"[{context}] Body contains '{marker}'",
                ))
                break

    return signals


# ---------------------------------------------------------------------------
# Main detection logic
# ---------------------------------------------------------------------------

class WAFResult(NamedTuple):
    url: str
    verdict: str         # DETECTED | PROBABLE | NOT_DETECTED | ERROR
    waf_name: str        # "" if not detected
    signals: list[WAFSignal]
    detail: str


def _detect_waf(url: str, timeout: float = 8.0) -> WAFResult:
    """Run WAF detection against a single URL."""
    # Normalise URL
    if not url.startswith(("http://", "https://")):
        url = "https://" + url

    # Pass 1: normal request
    status1, headers1, cookies1, body1 = _fetch(url, timeout=timeout)
    if status1 == -1:
        # Try HTTP
        http_url = url.replace("https://", "http://", 1)
        status1, headers1, cookies1, body1 = _fetch(http_url, timeout=timeout)
        if status1 == -1:
            return WAFResult(url=url, verdict="ERROR", waf_name="", signals=[],
                             detail="Connection failed on both HTTPS and HTTP")

    signals: list[WAFSignal] = _score_response(headers1, cookies1, body1, "normal")

    # Pass 2: probe request with a simple injection payload
    status2, headers2, cookies2, body2 = _fetch(url, extra_path=_PROBE_PAYLOAD, timeout=timeout)
    if status2 != -1:
        signals += _score_response(headers2, cookies2, body2, "probe")
        # Block signal: if probe gets a different status than normal (403, 406, 429, 503)
        if status2 in (403, 406, 429, 503) and status1 not in (403, 406, 429, 503):
            signals.append(WAFSignal(
                waf_name="(unknown)",
                source="body",
                detail=f"[probe] Request blocked with HTTP {status2} (normal was {status1})",
            ))

    if not signals:
        return WAFResult(url=url, verdict="NOT_DETECTED", waf_name="", signals=[],
                         detail="No WAF fingerprints detected in normal or probe responses")

    # Count unique WAF names (excluding "(unknown)")
    name_counts: dict[str, int] = {}
    for sig in signals:
        if sig.waf_name != "(unknown)":
            name_counts[sig.waf_name] = name_counts.get(sig.waf_name, 0) + 1

    if name_counts:
        top_name = max(name_counts, key=lambda k: name_counts[k])
        top_count = name_counts[top_name]
        verdict = "DETECTED" if top_count >= 2 else "PROBABLE"
    else:
        top_name = "(unknown)"
        verdict = "PROBABLE"

    detail = f"{len(signals)} signal(s) matched"
    if top_name != "(unknown)":
        detail += f"; strongest match: {top_name} ({name_counts.get(top_name, 0)} signal(s))"

    return WAFResult(url=url, verdict=verdict, waf_name=top_name, signals=signals, detail=detail)


# ---------------------------------------------------------------------------
# Report formatter
# ---------------------------------------------------------------------------

def _run_waf_detect(urls: str, timeout: float = 8.0) -> str:
    """Core detection callable directly in tests."""
    targets = [u.strip() for u in urls.replace(",", "\n").splitlines() if u.strip()]
    if not targets:
        return "[waf_detector] Error: no URLs provided"

    lines: list[str] = [f"[waf_detector] Checking {len(targets)} target(s)\n"]

    detected = probable = not_detected = errors = 0

    for url in targets:
        result = _detect_waf(url, timeout)
        lines.append("─" * 60)
        lines.append(f"URL    : {url}")
        lines.append(f"Verdict: {result.verdict}")
        if result.waf_name and result.waf_name != "(unknown)":
            lines.append(f"WAF    : {result.waf_name}")
        lines.append(f"Detail : {result.detail}")

        if result.signals:
            lines.append("Signals:")
            for sig in result.signals:
                src_tag = {"header": "HDR", "cookie": "CKI", "body": "BDY"}.get(sig.source, sig.source.upper())
                lines.append(f"  [{src_tag}] {sig.waf_name:20s}  {sig.detail}")

        lines.append("")

        if result.verdict == "DETECTED":
            detected += 1
        elif result.verdict == "PROBABLE":
            probable += 1
        elif result.verdict == "NOT_DETECTED":
            not_detected += 1
        else:
            errors += 1

    lines.append("─" * 60)
    lines.append(f"Summary: {detected} DETECTED, {probable} PROBABLE, {not_detected} NOT_DETECTED, {errors} ERROR")

    if detected or probable:
        lines.append(
            "\nNote: A detected WAF does not mean bypass is impossible — "
            "it informs evasion strategy (encoding, IP rotation, header manipulation, slow-rate probing)."
        )

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Function tool
# ---------------------------------------------------------------------------

@function_tool
def waf_detector(urls: str) -> str:
    """Detect Web Application Firewalls (WAF) in front of web targets.

    Passively fingerprints WAF products by analysing HTTP response headers,
    cookies, and body content.  Also sends a minimal probe request with a
    benign injection-like payload to trigger WAF block pages.

    Identifies: Cloudflare, AWS WAF/CloudFront, Akamai, Sucuri, Imperva/Incapsula,
    F5 BIG-IP, Barracuda, ModSecurity, Fortiweb, Wordfence, Radware AppWall,
    DDoS-Guard, Fastly, Nginx naxsi, and more via generic block-page detection.

    Args:
        urls: Newline- or comma-separated list of target URLs.
              Examples: "https://target.com" or "target.com, https://other.com"

    Returns:
        Formatted report with DETECTED / PROBABLE / NOT_DETECTED verdict per URL,
        the identified WAF product, and the signals that triggered the match.
    """
    return _run_waf_detect(urls)


TOOL_REGISTRY.register(
    "waf_detector",
    waf_detector,
    categories=["recon", "web"],
)
