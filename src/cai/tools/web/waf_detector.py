"""WAF (Web Application Firewall) detection tool for red team reconnaissance.

Identifies deployed WAF products by passively fingerprinting:
  - Response headers (vendor-specific header names and values)
  - Set-Cookie header names (vendor-specific session cookie names)
  - Response body markers (vendor-specific error page strings)
  - Probe responses (send a simple SQL-injection payload and analyse
    the error/block response for WAF signatures)

Severity / impact classifications:
  DETECTED     — High confidence: 2+ independent signals match
  PROBABLE     — Medium confidence: 1 signal matches
  NOT_DETECTED — No known WAF fingerprints found

Stdlib-only: http.client + urllib.  No external dependencies.
"""

